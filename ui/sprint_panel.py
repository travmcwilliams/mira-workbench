"""
ui/sprint_panel.py — sprint planning + CI controls for the Board page.
"""

from __future__ import annotations

import streamlit as st

from core import ci as ci_mod
from core import sprint as sprint_mod
from core.git_sync import ci_run_icon, remote_ci_status
from core.project import Project, list_project_index


def render_sprint_panel(project: Project) -> None:
    st.subheader("🏃 Sprint planning")

    cfg = sprint_mod.llm_config(project)
    c1, c2, c3 = st.columns([1, 1, 1])
    with c1:
        provider = st.selectbox(
            "Planner", ["offline", "ollama", "anthropic"],
            index=["offline", "ollama", "anthropic"].index(cfg.get("provider", "offline")),
            help="offline = deterministic template; ollama/anthropic = LLM-assisted",
        )
    with c2:
        capacity = st.number_input("Capacity (points)", min_value=0, value=0, step=1)
    with c3:
        materialize = st.checkbox("Create board tasks", value=False)

    if st.button("Generate sprint plan", type="primary"):
        with st.spinner("Planning sprint…"):
            plan = sprint_mod.plan_sprint(
                project,
                capacity=int(capacity) or None,
                provider=provider,
                materialize=materialize,
            )
        st.session_state["last_sprint_plan"] = plan
        if materialize:
            st.rerun()

    plan = st.session_state.get("last_sprint_plan")
    if plan:
        _render_plan(plan)


def _render_plan(plan: dict) -> None:
    st.markdown(f"**Goal:** {plan.get('goal', '')}")
    st.caption(f"Generated by: {plan.get('provider')}  ·  "
               f"{len(plan.get('stories', []))} stories  ·  "
               f"{plan.get('total_points', '?')} pts")

    for s in plan.get("stories", []):
        with st.expander(f"{s.get('title')}  ({s.get('points')} pts · {s.get('priority')})"):
            if s.get("as_a"):
                st.write(f"As a {s.get('as_a')}, I want {s.get('i_want', '')}"
                         f"{(' so that ' + s['so_that']) if s.get('so_that') else ''}.")
            for c in s.get("acceptance_criteria", []):
                st.write(f"- [ ] {c}")
            if s.get("risks"):
                st.caption("⚠️ " + ", ".join(s["risks"]))
            if s.get("blockers"):
                st.caption("⛔ " + ", ".join(s["blockers"]))

    md = sprint_mod.export_markdown(plan)
    js = sprint_mod.export_json(plan)
    d1, d2 = st.columns(2)
    with d1:
        st.download_button("⬇ Markdown", md, file_name="sprint_plan.md",
                           mime="text/markdown")
    with d2:
        st.download_button("⬇ JSON", js, file_name="sprint_plan.json",
                           mime="application/json")


def render_ci_panel(project: Project) -> None:
    st.subheader("⚙️ CI / gated pipeline")
    ci_cfg = ci_mod.ci_config(project)
    gates = ci_cfg.get("gates", [])
    if gates:
        for g in gates:
            st.caption(f"Gate: {g.get('stage')}.{g.get('metric')} "
                       f"{g.get('op')} {g.get('threshold')}")
    else:
        st.caption("No gates configured (edit meta['ci']['gates']).")

    if st.button("Run gated CI"):
        with st.spinner("Running gated pipeline…"):
            result = ci_mod.run_ci(project)
        if result.status == "passed":
            st.success(f"CI passed · stages: {', '.join(result.stages_run)}")
        elif result.status == "failed":
            g = result.failed_gate
            st.error(f"CI failed at gate {g.gate if g else '?'} ({g.message if g else ''})")
        else:
            st.error(f"CI error at {result.failed_stage}: {(result.error or '')[:200]}")

    st.divider()
    _render_remote_ci(project)


def _render_remote_ci(project: Project) -> None:
    st.subheader("☁️ Remote CI (GitHub Actions)")
    status = remote_ci_status(project)
    if not status.get("available"):
        st.caption(f"Unavailable: {status.get('error', 'unknown')}")
        return
    runs = status.get("runs") or []
    if not runs:
        st.caption("No workflow runs found for this repo.")
        return
    for r in runs:
        state = r.get("conclusion") or r.get("status") or "?"
        line = (f"{ci_run_icon(r)} **{r.get('workflow', '?')}** · {state} · "
                f"{r.get('branch', '?')} · {r.get('title', '')[:60]}")
        url = r.get("url")
        st.markdown(f"{line}  \n{url}" if url else line)
